// Generates and PROVES all 100 PARALLAX puzzles (each is solved by the engine and the solution replayed) and writes games/px/data/puzzles.js
import fs from 'node:fs';
import { makeLevel, planFor } from '../games/px/gen.js';
import { solve, replay } from '../games/px/logic.js';
const only = process.argv[2] ? +process.argv[2] : null, out = [];
for (let n = 1; n <= 100; n++) {
  if (only && n !== only) continue;
  const t0 = Date.now(), st = makeLevel(n), sol = solve(st), ok = sol && replay(st, sol).ok;
  if (!ok) throw new Error('level ' + n + ' unsolved');
  out.push({ n, f: planFor(n).f, par: sol.length, state: st, sol });
  console.log(n, planFor(n).f, 'par', sol.length, (Date.now() - t0) + 'ms');
}
if (!only) fs.writeFileSync('games/px/data/puzzles.js', '/* Generated by tools/gen-parallax.mjs. Every puzzle here has been solved and replayed by the engine. */\nexport const PUZZLES = ' + JSON.stringify(out) + ';\n');
